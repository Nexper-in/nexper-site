def lang_picker():
    """Language dropdown. assets/i18n.js reads the options from here."""
    items = ""
    for l in LANGS:
        font = f' data-font="{l["font"]}"' if l.get("font") else ""
        sub = f'<span class="lang-en">{l["english"]}</span>' if l["code"] != "en" else ""
        items += (
            f'<li><button type="button" role="menuitemradio" aria-checked="false" data-lang-option="{l["code"]}"'
            f' data-html-lang="{l["htmlLang"]}"{font} lang="{l["htmlLang"]}">'
            f'<span class="lang-native">{l["name"]}</span>{sub}{ico("check", "ico lang-tick")}</button></li>'
        )
    first = LANGS[0]["name"]
    return f"""<div class="lang-menu" data-lang-menu>
        <button type="button" class="lang-btn" aria-haspopup="true" aria-expanded="false" aria-label="{t("nav.language")}" data-i18n-attr="aria-label:nav.language">{ico("globe")}<span data-lang-current>{first}</span>{ico("chevron-down", "ico lang-chevron")}</button>
        <ul class="lang-list" role="menu" hidden>{items}</ul>
      </div>"""



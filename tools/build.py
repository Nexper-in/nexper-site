"""Builds the static pages of nexper.in and checks the translations.

All visible text lives in i18n/<lang>.json. English (i18n/en.json) is the
source; the pages are generated with English text plus data-i18n keys, and
assets/i18n.js swaps in the visitor's language in the browser.

    python3 tools/build.py           # regenerate the HTML pages
    python3 tools/build.py --check   # fail if pages or translations are out of date (CI runs this)
    python3 tools/build.py --stamp   # after updating every language, record that they match English

Never edit the generated .html files by hand: change this file or the JSON.
"""


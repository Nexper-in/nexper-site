def load_json(name):
    with open(os.path.join(I18N, name), encoding="utf-8") as f:
        return json.load(f)


LANGS = load_json("languages.json")
EN = load_json("en.json")
USED = set()


def t(key):
    """English text for a key. Records the key so unused keys can be reported."""
    if key not in EN:
        raise SystemExit(f"Missing key in i18n/en.json: {key}")
    USED.add(key)
    return EN[key]


def tag(name, key, cls=None, extra=""):
    """<name data-i18n="key">English</name>"""
    c = f' class="{cls}"' if cls else ""
    return f'<{name}{c} data-i18n="{key}"{extra}>{t(key)}</{name}>'


def asset_version():
    h = hashlib.sha1()
    for rel in ("assets/site.css", "assets/site.js", "assets/i18n.js", "assets/icons.svg"):
        with open(os.path.join(ROOT, rel), "rb") as f:
            h.update(f.read())
    for lang in LANGS:
        p = os.path.join(I18N, f"{lang['code']}.json")
        if os.path.exists(p):
            with open(p, "rb") as f:
                h.update(f.read())
    return h.hexdigest()[:8]


V = asset_version()


def ico(name, cls="ico"):
    return f'<svg class="{cls}" aria-hidden="true"><use href="/assets/icons.svg?v={V}#{name}"/></svg>'


# ---------------------------------------------------------------- layout


def head(title_key, desc_key, path, raw=None):
    """Page <head>. raw=(title, description) for English-only pages."""
    codes = [l["code"] for l in LANGS]
    if raw:
        title, desc = (html.escape(x, quote=True) for x in raw)
        title_attr = desc_attr = ""
    else:
        title = html.escape(t(title_key), quote=True)
        desc = html.escape(t(desc_key), quote=True)
        title_attr = f' data-i18n="{title_key}"'
        desc_attr = f' data-i18n-attr="content:{desc_key}"'

    return f"""<!doctype html>
<html lang="en-IN">
{GENERATED_NOTE}
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title{title_attr}>{title}</title>
<meta name="description" content="{desc}"{desc_attr}>
<link rel="canonical" href="{SITE}{path}">
<meta name="theme-color" content="#08070f">
<link rel="icon" href="/icon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Nexper">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{desc}">
<meta property="og:url" content="{SITE}{path}">
<meta property="og:image" content="{SITE}/og.jpg">
<meta property="og:locale" content="en_IN">
<meta name="twitter:card" content="summary_large_image">
<script>
  // Hide the page briefly while a saved non-English language loads, so
  // visitors don't see English flash first. assets/i18n.js clears this.
  (function () {{
    var codes = {json.dumps(codes[1:])};
    var l = null;
    try {{ l = new URLSearchParams(location.search).get("lang") || localStorage.getItem("nexper.lang"); }} catch (e) {{}}
    if (!l && navigator.languages) {{
      for (var i = 0; i < navigator.languages.length && !l; i++) {{
        var c = navigator.languages[i].slice(0, 2).toLowerCase();
        if (c === "en" || codes.indexOf(c) > -1) l = c;
      }}
    }}
    if (l && codes.indexOf(l) > -1) {{
      var d = document.documentElement;
      d.setAttribute("data-lang-pending", "");
      setTimeout(function () {{ d.removeAttribute("data-lang-pending"); }}, 2500);
    }}
  }})();
</script>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=DM+Sans:opsz,wght@9..40,400;9..40,500;9..40,600;9..40,700&family=Manrope:wght@700;800&display=swap" rel="stylesheet">
<link rel="stylesheet" href="/assets/site.css?v={V}">
</head>
<body>
<a class="skip" href="#main" data-i18n="skip">{t("skip")}</a>
"""



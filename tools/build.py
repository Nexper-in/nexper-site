# ---------------------------------------------------------------- checks

TAG_RE = re.compile(r"<\s*(/?)\s*([a-zA-Z0-9]+)[^>]*>")
HREF_RE = re.compile(r'href="([^"]*)"')
STAMP_FILE = os.path.join(I18N, "_source-hashes.json")


def markup_signature(s):
    return sorted(m.group(1) + m.group(2).lower() for m in TAG_RE.finditer(s)), sorted(HREF_RE.findall(s))


def en_hash(s):
    return hashlib.sha1(s.encode("utf-8")).hexdigest()[:10]


def check_translations():
    errors = []
    en_keys = set(EN)
    unused = en_keys - USED
    for k in sorted(unused):
        errors.append(f"en.json: key '{k}' is not used by any page (remove it, or use it in tools/build.py)")
    stamps = load_json("_source-hashes.json") if os.path.exists(STAMP_FILE) else {}
    for lang in LANGS[1:]:
        code = lang["code"]
        path = os.path.join(I18N, f"{code}.json")
        if not os.path.exists(path):
            errors.append(f"{code}.json is missing")
            continue
        data = load_json(f"{code}.json")
        for k in sorted(en_keys - set(data)):
            errors.append(f"{code}.json: missing translation for '{k}'")
        for k in sorted(set(data) - en_keys):
            errors.append(f"{code}.json: '{k}' is not in en.json (remove it)")
        for k in sorted(en_keys & set(data)):
            if not str(data[k]).strip():
                errors.append(f"{code}.json: '{k}' is empty")
            elif markup_signature(data[k]) != markup_signature(EN[k]):
                errors.append(f"{code}.json: '{k}' must keep the same HTML tags and links as English")
    for k in sorted(en_keys):
        if stamps.get(k) != en_hash(EN[k]):
            errors.append(
                f"'{k}' is new or its English text changed since the translations were last confirmed. "
                "Update it in every language, then run: python3 tools/build.py --stamp"
            )
    return errors


def render_all():
    USED.clear()
    return {rel: fn() for rel, fn in PAGES.items()}


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "build"
    pages = render_all()
    if mode == "--stamp":
        errors = [e for e in check_translations() if "--stamp" not in e]
        if errors:
            print("Fix these before stamping:\n  " + "\n  ".join(errors))
            sys.exit(1)
        with open(STAMP_FILE, "w", encoding="utf-8") as f:
            json.dump({k: en_hash(v) for k, v in sorted(EN.items())}, f, indent=2, ensure_ascii=False)
            f.write("\n")
        print(f"Stamped {len(EN)} keys as translated in all languages.")
        return
    if mode == "--check":
        errors = check_translations()
        for rel, content in pages.items():
            p = os.path.join(ROOT, rel)
            if not os.path.exists(p) or open(p, encoding="utf-8").read() != content:
                errors.append(f"{rel} is out of date: run python3 tools/build.py and commit the result")
        if errors:
            print(f"{len(errors)} problem(s):\n  " + "\n  ".join(errors))
            sys.exit(1)
        print(f"OK: {len(pages)} pages up to date, {len(EN)} keys translated into {len(LANGS) - 1} languages.")
        return
    for rel, content in pages.items():
        p = os.path.join(ROOT, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as f:
            f.write(content)
    problems = check_translations()
    print(f"Built {len(pages)} pages (asset version {V}).")
    if problems:
        print(f"Translation check: {len(problems)} problem(s). Run --check for the list.")


if __name__ == "__main__":
    main()
